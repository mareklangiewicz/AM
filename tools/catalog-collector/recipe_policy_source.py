"""Compile literal recipe declarations into trusted awk data, never selector code."""
import json
from pathlib import Path

from recipe_declarations import recipe_rows

ROOT = Path(__file__).resolve().parents[2]
START = '# BEGIN recipe declarations\n'
END = '# END recipe declarations\n'


def generate():
    lines = [START.rstrip(), '# Generated by recipe_policy_source.py; edit recipe declarations.', 'BEGIN {']
    for row in recipe_rows(ROOT):
        key = json.dumps(row['recipe'])
        fields = dict(repository=str(row['repository_id']), channel=row['channel'],
                      pattern=row['asset_pattern'], tools=' '.join(row.get('tools', [])),
                      tool_suffix=row.get('tool_asset_suffix', ''),
                      fresh_only=int(row['fresh_only']))
        for name, value in fields.items():
            lines.append('    recipes_'+name+'['+key+']='+json.dumps(value))
    lines += ['}', END.rstrip(), '']
    path = ROOT/'modules/catalog-yaml-policy.am'
    source = path.read_text()
    if source.count(START) != 1 or source.count(END) != 1:
        raise ValueError('missing or duplicate declaration registry seam')
    before, rest = source.split(START)
    _, after = rest.split(END)
    path.write_text(before+'\n'.join(lines)+after)


if __name__ == '__main__':
    generate()
