"""Compile literal recipe declarations into trusted awk data, never selector code."""
import json
from pathlib import Path

from recipe_declarations import recipe_rows, url_policy_rows

ROOT = Path(__file__).resolve().parents[2]
START = '# BEGIN recipe declarations\n'
END = '# END recipe declarations\n'


def generate():
    lines = [START.rstrip(), '# Generated by recipe_policy_source.py; edit recipe declarations.', 'BEGIN {']
    groups={}
    seen=set();dispatches={}
    for row in recipe_rows(ROOT)+url_policy_rows(ROOT):
        if row['recipe'] in seen:raise ValueError('duplicate selection policy')
        seen.add(row['recipe'])
        key = json.dumps(row['recipe'])
        fields = dict(repository=str(row['repository_id']), channel=row['channel'],
                      pattern=row['asset_pattern'], tools=' '.join(row.get('tools', [])),
                      tool_suffix=row.get('tool_asset_suffix', ''),
                      fresh_only=int(row['fresh_only']))
        for name, value in fields.items():
            lines.append('    recipes_'+name+'['+key+']='+json.dumps(value))
        if row['catalog_app']!=row['app']:
            lines.append('    recipes_catalog_app['+key+']='+json.dumps(row['catalog_app']))
        for alias in row.get('source_aliases',[]):
            identity=(row['dispatch_recipe'],alias.lower())
            if identity in dispatches and dispatches[identity]!=row['recipe']:
                raise ValueError('ambiguous recipe source dispatch')
            dispatches[identity]=row['recipe']
            dispatch=json.dumps(identity[0])+','+json.dumps(identity[1])
            lines.append('    recipes_source_policy['+dispatch+']='+key)
        if 'url_rules' in row:
            rules=json.dumps(row['url_rules'],sort_keys=True)
            group=groups.setdefault(rules,len(groups)+1)
            lines.append('    recipes_url_group['+key+']='+str(group))
    for rules,group in groups.items():
        rules=json.loads(rules)
        lines.append(f'    url_rule_count[{group}]={len(rules)}')
        for index,rule in enumerate(rules,1):
            key=f'{group},{index}'
            for name,value in rule.items():
                if name=='pattern' and rule['ignore_case']:value=value.lower()
                if type(value) is bool:value=int(value)
                lines.append('    url_rule_'+name+'['+key+']='+json.dumps(value))
    lines += ['}', END.rstrip(), '']
    path = ROOT/'modules/catalog-yaml-policy.am'
    source = path.read_text()
    if source.count(START) != 1 or source.count(END) != 1:
        raise ValueError('missing or duplicate declaration registry seam')
    before, rest = source.split(START)
    _, after = rest.split(END)
    path.write_text(before+'\n'.join(lines)+after)


if __name__ == '__main__':
    generate()
